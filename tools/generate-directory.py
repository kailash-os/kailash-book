#!/usr/bin/env python3
"""generate-directory.py — regenerate recipes/directory.qmd from the recipe files.

Wave-2 mechanical core of the directory lane (kailash-book#10, #15):
every recipe's header TABLE (Field | Value) is parsed for Section /
Level / Tools; the directory page (counts + per-section listing) is
generated from those parses. Zero hand-maintained rows.

Contract:
- reads recipes/**/*.qmd (skips directory.qmd itself and index.qmd)
- parses the YAML title + the first md table's Tool(s)/Section/Level rows
- sections are the five theme sections (sections-for-life rule, ADR-0001);
  a recipe whose table names an unknown section fails the run (no silent drift)
- writes recipes/directory.qmd; a comment banner marks it generated
"""
import re
import sys
from collections import OrderedDict
from pathlib import Path

SECTIONS = OrderedDict([
    ("Getting started", []),
    ("Scanning", []),
    ("Attack–defence pairs", []),
    ("Ops", []),
    ("Administrator", []),
])
SECTION_ALIASES = {
    "getting started": "Getting started",
    "scanning": "Scanning",
    "attack–defence pairs": "Attack–defence pairs",
    "attack-defence pairs": "Attack–defence pairs",
    "ops": "Ops",
    "administrator": "Administrator",
}

def parse_recipe(path: Path):
    text = path.read_text(encoding="utf-8")
    m = re.search(r'^title:\s*"Recipe:\s*(.*?)"\s*$', text, re.M)
    if not m:
        return None
    title = m.group(1).strip()
    # first md table in body
    table = re.search(r'^\| Field \| Value \|\s*\n\|[-| ]+\|\s*\n((?:\|.*\n)+?(?:\n|\Z))', text, re.M)
    fields = {}
    if table:
        for row in table.group(1).strip().splitlines():
            cells = [c.strip() for c in row.strip().strip('|').split('|')]
            if len(cells) >= 2 and cells[0] in ("Tool", "Tools", "Section", "Level", "Tags"):
                fields[cells[0]] = re.sub(r'`([^`]*)`', r'\1', cells[1])
    tool = fields.get("Tool") or fields.get("Tools") or "(pair/cluster)"
    section_raw = fields.get("Section", "")
    section = SECTION_ALIASES.get(section_raw.lower().strip())
    level = fields.get("Level", "?").strip().lower()
    if section is None or level not in ("easy", "medium", "hard"):
        print(f"WARN {path}: unmappable section ({section_raw!r}) or level ({level!r})", file=sys.stderr)
        return None
    # relative link from recipes/<section>/x.qmd to directory.qmd
    rel = f"{path.parent.name}/{path.stem}.html"
    return dict(title=title, tool=tool, section=section, level=level, rel=rel)

def main():
    root = Path(__file__).resolve().parent.parent
    recipes_root = root / "recipes"
    entries = []
    for path in sorted(recipes_root.rglob("*.qmd")):
        if path.name in ("directory.qmd",):
            continue
        e = parse_recipe(path)
        if e:
            entries.append(e)
    for sec in SECTIONS:
        SECTIONS[sec] = [e for e in entries if e["section"] == sec]
    total = sum(len(v) for v in SECTIONS.values())
    counts = {lv: sum(1 for e in entries if e["level"] == lv) for lv in ("easy", "medium", "hard")}

    lines = []
    lines.append("---")
    lines.append('title: "Recipe directory"')
    lines.append("---")
    lines.append("")
    lines.append("<!-- GENERATED by tools/generate-directory.py — do not edit by hand;")
    lines.append(f"     regenerated from {total} recipe header tables. -->")
    lines.append("")
    lines.append("One page indexing every recipe: theme section, level, tools used.")
    lines.append("Counts and listings regenerate from the recipe header tables at")
    lines.append("build time — this page is a generated artifact, never hand-counted.")
    lines.append("")
    lines.append("## At a glance")
    lines.append("")
    lines.append("| Section | Recipes | Easy | Medium | Hard |")
    lines.append("|---|---|---|---|---|")
    for sec, es in SECTIONS.items():
        c = {lv: sum(1 for e in es if e["level"] == lv) for lv in ("easy", "medium", "hard")}
        lines.append(f"| {sec} | {len(es)} | {c['easy']} | {c['medium']} | {c['hard']} |")
    lines.append(f"| **Total** | **{total}** | **{counts['easy']}** | **{counts['medium']}** | **{counts['hard']}** |")
    lines.append("")
    for sec, es in SECTIONS.items():
        lines.append(f"## {sec}")
        lines.append("")
        lines.append("| Recipe | Level | Tools |")
        lines.append("|---|---|---|")
        for e in es:
            lines.append(f"| [{e['title']}]({e['rel']}) | {e['level']} | {e['tool']} |")
        lines.append("")
    lines.append("## Top-10 collections (generated views, planned)")
    lines.append("")
    lines.append("Per the organisation ADR, Top-10 collections render as build-time")
    lines.append("generated index pages over recipe tags — recipes never move between")
    lines.append("sections. Planned sets: OWASP LLM Top-10 (the scanning/pair recipes")
    lines.append("already carry epoch-mapped tags; mappings per manifest row), OWASP")
    lines.append("ML Top-10, OWASP API Top-10. No collection page renders until its")
    lines.append("tagged recipes exist — never an empty view.")
    lines.append("")
    out = root / "recipes" / "directory.qmd"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}: {total} recipes ({counts['easy']} easy / {counts['medium']} medium / {counts['hard']} hard)")

if __name__ == "__main__":
    main()
